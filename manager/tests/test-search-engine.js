const assert=require('node:assert/strict');
const engine=require('../assets/search-engine.js');
const tag={name:'frieren',tag_cn:'芙莉莲',tag_cn_long:'《葬送的芙莉莲》人物',prompt:'1girl, white_hair',groups:['roles']};
const fern={...tag,name:'fern',tag_cn:'菲伦'};
assert.deepEqual(engine.terms('pink hair，long_hair, ELF'),['pink','hair','long_hair','elf']);
assert.equal(engine.matches(fern,engine.terms('芙莉莲')),false);
assert.equal(engine.matches(fern,engine.terms('芙莉莲'),{matchLongDescription:true}),true);
assert.equal(engine.matches(tag,engine.terms('white hair')),false);
assert.equal(engine.matches(tag,engine.terms('white hair'),{characterLibrary:true}),true);
assert.equal(engine.matches({name:'pink_hair'},engine.terms('pink hair')),true);
assert.equal(engine.matches({name:'pink-hair'},engine.terms('pink_hair')),true);
assert.equal(engine.matches({name:'pink hair'},engine.terms('pink blue')),false);
const groups=[{id:'roles',name_cn:'角色',search_enabled:false}];
assert.equal(engine.visible(tag,groups,{currentGroup:'all'}),false);
assert.equal(engine.visible(tag,groups,{currentGroup:'roles'}),true);
assert.equal(engine.visible(tag,groups,{characterLibrary:true,currentGroup:'character_all'}),true);
assert.equal(engine.isCharacterGroup(groups[0]),true);
const activeRoles=[{id:'cg_honkai_star_rail_characters',name_cn:'崩坏：星穹铁道角色',search_enabled:true}];
const character={name:'fu_xuan_(honkai:_star_rail)',tag_cn:'符玄',groups:[activeRoles[0].id]};
assert.equal(engine.visible(character,activeRoles,{currentGroup:'all',excludeCharacters:true}),false);
assert.equal(engine.visible(character,activeRoles,{characterLibrary:true,currentGroup:'character_all',excludeCharacters:false}),true);
assert.equal(engine.visible({name:'pink_hair',groups:[]},activeRoles,{currentGroup:'all',excludeCharacters:true}),true);
assert.equal(engine.visible(tag,groups,{currentGroup:'roles',excludeCharacters:true}),false);
assert.equal(engine.matchesModel({name:'bin',file_path:'D:/models/anima/bin.safetensors'},'anima/bin'),true);
assert.equal(engine.matchesModel({name:'model',prompt_sets:[{name:'日常服',prompt:'casual'},{name:'战斗服',prompt:'armor'}]},'战斗服'),true);
assert.equal(engine.matchesModel({name:'model',prompt_sets:[{name:'日常服',prompt:'casual'},{name:'战斗服',prompt:'armor'}]},'armor'),true);
const confidenceLevels=['MANUAL','A','B','C','D'];
confidenceLevels.forEach((minimum,minRank)=>{
  confidenceLevels.forEach((value,rank)=>assert.equal(engine.matchesConfidence(value,minimum),rank<=minRank));
  confidenceLevels.forEach((unrated,rank)=>assert.equal(engine.matchesConfidence('',minimum,unrated),rank<=minRank));
});
assert.equal(engine.matchesConfidence('','B'),false);
assert.equal(engine.matchesConfidence('','none','MANUAL'),true);
assert.equal(engine.matchesConfidence('MANUAL','none'),false);
assert.equal(engine.matchesConfidence('','all'),true);
assert.deepEqual(confidenceLevels.map(value=>engine.confidenceRank(value)),[0,1,2,3,4]);
console.log('Shared search engine: matching and confidence checks passed');
